"""Prepare generated lower-body inserts without replacing any source asset."""
from pathlib import Path
from PIL import Image, ImageChops, ImageDraw
import base64
import hashlib
import json
import io

HERE = Path(__file__).resolve().parent
OUT = HERE / 'drawing_02'
approval_path = OUT / 'approval.json'
approval = json.loads(approval_path.read_text(encoding='utf-8')) if approval_path.exists() else None
SOURCE = HERE.parents[2] / 'finn_pet' / 'frames' / 'running-left'
CUT = 130
GROUND = 202
PAIRS = [('focused_landing', 0, 1), ('passing_a', 1, 2), ('landing_b', 4, 5), ('passing_b', 5, 6)]
original = [Image.open(SOURCE / f'{i:02d}.png').convert('RGBA') for i in range(8)]
records = []
new_frames = []
for name, first, second in PAIRS:
    raw_path = OUT / f'{name}.png'
    generated = Image.open(raw_path).convert('RGBA').resize((192,208), Image.Resampling.LANCZOS)
    alpha = generated.getchannel('A')
    core = alpha.point(lambda a: 255 if a >= 32 else 0)
    core_box = core.getbbox()
    gen_waist = alpha.point(lambda a: 255 if a >= 128 else 0).crop((0,CUT,192,CUT+1)).getbbox()
    source_waist = original[first].getchannel('A').point(lambda a: 255 if a >= 128 else 0).crop((0,CUT,192,CUT+1)).getbbox()
    if not core_box or not gen_waist or not source_waist:
        raise ValueError('Missing generated waist or body')
    x_scale = (source_waist[2]-source_waist[0]) / (gen_waist[2]-gen_waist[0])
    y_scale = (GROUND+1-CUT) / (core_box[3]-CUT)
    x_offset = source_waist[0] - gen_waist[0]*x_scale
    # The artistic content is generated by Imagegen. This affine fit only
    # registers that insert to the existing sprite waist and ground line.
    lower = generated.transform((192,208), Image.Transform.AFFINE,
        (1/x_scale,0,-x_offset/x_scale,0,1/y_scale,CUT-CUT/y_scale), Image.Resampling.BICUBIC)
    lower.paste((0,0,0,0), (0,0,192,CUT))
    lower.paste((0,0,0,0), (0,GROUND+1,192,208))
    result = Image.new('RGBA',(192,208))
    result.alpha_composite(lower)
    result.paste(original[first].crop((0,0,192,CUT)), (0,0))
    result.save(OUT / f'{name}_prepared.png')
    data = io.BytesIO()
    result.save(data, format='WEBP', lossless=True, exact=True)
    webp = data.getvalue()
    (OUT / f'{name}_prepared.webp').write_bytes(webp)
    decoded = Image.open(io.BytesIO(webp)).convert('RGBA')
    if decoded.tobytes() != result.tobytes():
        raise ValueError('Lossless insert decode mismatch')
    if result.crop((0,0,192,CUT)).tobytes() != original[first].crop((0,0,192,CUT)).tobytes():
        raise ValueError('Original upper body changed')
    new_frames.append(result)
    records.append({'name':name,'betweenSourceFrames':[first,second],
        'generatedRaw':raw_path.name,'generatedRawSha256':hashlib.sha256(raw_path.read_bytes()).hexdigest(),
        'preparedPng':f'{name}_prepared.png','preparedWebp':f'{name}_prepared.webp',
        'upperBodySource':first,'upperBodyRowsUnchanged':[0,CUT-1],
        'insertRegistration':{'cutY':CUT,'groundY':GROUND,'xScale':x_scale,'yScale':y_scale,'xOffset':x_offset},
        'visibleAlphaBounds':result.getchannel('A').getbbox(),
        'pngSha256':hashlib.sha256((OUT / f'{name}_prepared.png').read_bytes()).hexdigest()})

bank = []
for frame in original:
    encoded = io.BytesIO()
    frame.save(encoded, format='WEBP', lossless=True, exact=True)
    roundtrip = Image.open(io.BytesIO(encoded.getvalue())).convert('RGBA')
    if roundtrip.tobytes() != frame.tobytes():
        raise ValueError('Source image roundtrip mismatch')
    bank.append('data:image/webp;base64,' + base64.b64encode(encoded.getvalue()).decode('ascii'))
bank += ['data:image/webp;base64,' + base64.b64encode((OUT / f'{name}_prepared.webp').read_bytes()).decode('ascii') for name,_,_ in PAIRS]
orders = [list(range(8)), [0,8,1,9,2,3,4,10,5,11,6,7]]
durations = [[120]*7+[220], [65,65,70,70,130,130]*2]
template = (HERE / 'comparison.template.html').read_text(encoding='utf-8')
template = template.replace('finn-left-comparison','finn-left-drawing-comparison')
template = template.replace('Dezelfde 8 frames · lus van 1060 ms','12 frames · lus van 1060 ms')
template = template.replace('Timingproef 01 · kandidaat voor gezamenlijke afstemming met rechts.', 'Tekenproef 02 · vier nieuwe tussenposes · nog te beoordelen.')
template = template.replace('Finn met gelijkmatiger timing van de linkerloop','Finn met nieuw getekende tussenposes voor de benen')
template = template.replace('const frames = __FRAMES_JSON__;', 'const frames = __FRAMES_JSON__;\n  const orders = '+json.dumps(orders)+';')
template = template.replace('displays[index].src = frames[frame];','displays[index].src = frames[orders[index][frame]];')
template = template.replace("+' van 8 · '+list[frame]", "+' van '+list.length+' · '+list[frame]")
template = template.replace('Finn links: 8 oorspronkelijke PNG beelden, gedeelde klok, beide lussen 1060 ms.', 'Finn links tekenproef: 8 bronbeelden en 4 echte beenposes; beide lussen 1060 ms.')
html = template.replace('__FRAMES_JSON__',json.dumps(bank)).replace('__DURATIONS_JSON__',json.dumps(durations))
if approval:
    html = html.replace('Tekenproef 02 · vier nieuwe tussenposes · nog te beoordelen.', 'Tekenproef 02 · goedgekeurd voor overname.')
if len(html)>512000 or any(sum(d)!=1060 for d in durations):
    raise ValueError('Invalid HTML budget or duration')
(OUT / 'comparison.html').write_text(html,encoding='utf-8')
(OUT / 'comparison.template.html').write_text(template,encoding='utf-8')
contact = Image.new('RGBA',(768,4*240),(242,242,238,255))
draw = ImageDraw.Draw(contact)
for row, ((name,a,b), frame) in enumerate(zip(PAIRS,new_frames)):
    for col, (label,im) in enumerate([(f'Source {a:02d}',original[a]),('New legs',frame),(f'Source {b:02d}',original[b])]):
        draw.text((col*256+5,row*240+5),label,fill=(20,20,20,255))
        contact.alpha_composite(im,(col*256+32,row*240+26))
contact.save(OUT / 'prepared_contact.png')
manifest = {'candidate':'drawing_02','status':'approved' if approval else 'unapproved','approval':approval,'kind':'generated_lower_body_inserts',
    'sourceFrameCount':8,'newUniquePoseCount':4,'candidateFrameCount':12,'cellSize':[192,208],
    'sourceDurationsMs':durations[0],'candidateDurationsMs':durations[1],'candidateOrder':orders[1],
    'sourceFrames':[{'path':'docs/design/finn_pet/frames/running-left/'+f'{i:02d}.png',
                     'sha256':hashlib.sha256((SOURCE / f'{i:02d}.png').read_bytes()).hexdigest()} for i in range(8)],
    'embeddedFormat':'Lossless WebP, full RGBA roundtrip verified for all 12 frames; original PNG files unmodified',
    'frameBank':['source '+str(i) for i in range(8)]+[p[0] for p in PAIRS],
    'loopDurationMs':1060,'halfCycleMs':530,'newPoses':records,
    'generation':'Built-in imagegen, original Finn endpoint PNG references. Four separate targeted generations after a discarded four-pose sheet.',
    'assembly':'Only generated legs below row 130 inserted. Original head, glasses, torso, hands and map above row 130 retained byte-for-byte. Generated legs affinely fitted at waist and ground; no crossfade or optical interpolation.',
    'limitations':['Transitions 02 to 03 and 06 to 07 still use adjacent original drawings.', 'Waist joins, foot travel and knee paths require visual review.', 'Original 07 to 00 drawings preserved; final-frame hold shortened by timing only.', 'Candidate internal timing still requires coordination with the right-hand walking cycle.'],
    'htmlCharacters':len(html),'externalImageResources':0}
(OUT / 'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
print(json.dumps({'htmlCharacters':len(html),'poses':records,'candidateDurationsMs':durations[1]}))
